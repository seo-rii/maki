#!/usr/bin/env python3
"""Round-8 audit (long-seeds): generate salted copies of every committed
randomized integration test.

For each crate, the committed test files that seed an RNG are copied to
tests/audit8_salted/<stem>.rs with one mechanical change: every
`seed_from_u64(X)` becomes `seed_from_u64(crate::a8_salt() ^ X)` (and the two
hand-rolled LCGs in maki-backing get the same XOR).  tests/audit8_salted.rs
mounts the copies as modules.  With AUDIT8_SALT unset (or 0) every copy is the
committed test, bit for bit; with AUDIT8_SALT=n every randomized test, sweep
and release gate runs its committed body and iteration count on fresh seeds.

Run one module per process (the originals are separate test binaries):
  AUDIT8_SALT=7 <binary> review_r3b_durability:: --test-threads=1 [--include-ignored]
"""
import os, re, sys

W = '/home/user/wt/audit8'
CRATES = {
    'maki-core': ['review_r3b_durability', 'review_trim_power_loss', 'phase3', 'phase4',
                  'phase11_dbsim', 'phase12_powerloss', 'review_stress', 'review_corruption',
                  'review_discard_crash', 'review_discard_model', 'review_discard_storage',
                  'review_discard_engine', 'review_journal_torn_header',
                  'review_journal_legacy_torn_header', 'review_recovery_batch_latest',
                  'review_recovery_prefix_rewrite', 'review_superblock_durability',
                  'review_checkpoint_raise', 'review_checkpoint_concurrency', 'review_ab_retry',
                  'review_audit'],
    'maki-test-support': ['phase0', 'review_crash_writeback', 'review_crash_posix',
                          'review_namespace_history', 'review_crash_handles'],
    'maki-format': ['review_fuzz', 'phase1', 'review_ab_retry', 'review_journal_progress'],
    'maki-crypto': ['review_stress_crypto', 'phase5_flow', 'review_jitter_progress'],
    'maki-cache': ['review_cache_model'],
    'maki-backing': ['rollback_model', 'remote_rollback'],
    # 'maki-crypto-http': ['review_fuzz_transport'],  # not generated: never built (heavy deps, disk)
}

def patch(src, crate, stem):
    n = src.count('seed_from_u64(')
    out = src.replace('seed_from_u64(', 'seed_from_u64(crate::a8_salt() ^ ')
    extra = 0
    if crate == 'maki-backing' and stem == 'rollback_model':
        assert 'Lcg(seed)' in out
        extra += out.count('Lcg(seed)')
        out = out.replace('Lcg(seed)', 'Lcg(seed ^ crate::a8_salt())')
    if crate == 'maki-backing' and stem == 'remote_rollback':
        # `let mut seed = <const>;` ahead of the LCG step loop
        m = re.search(r'let mut seed(: u64)? = ([^;]+);', out)
        assert m, 'remote_rollback seed'
        out = out[:m.start()] + f'let mut seed{m.group(1) or ""} = ({m.group(2)}) ^ crate::a8_salt();' + out[m.end():]
        extra += 1
    # relative references now live one directory deeper
    out = re.sub(r'#\[path = "([^"]+)"\]', r'#[path = "../\1"]', out)
    def modfix(m):
        name = m.group(2)
        tests = f'{W}/crates/{crate}/tests'
        if os.path.exists(f'{tests}/{name}.rs'):
            return f'{m.group(1)}#[path = "../{name}.rs"]\n{m.group(1)}mod {name};'
        if os.path.exists(f'{tests}/{name}/mod.rs'):
            return f'{m.group(1)}#[path = "../{name}/mod.rs"]\n{m.group(1)}mod {name};'
        return m.group(0)
    out = re.sub(r'(?m)^(\s*)mod ([a-z_0-9]+);', modfix, out)
    out = re.sub(r'(include(?:_str|_bytes)?!\(")', r'\1../', out)
    return out, n + extra

for crate, stems in CRATES.items():
    tests = f'{W}/crates/{crate}/tests'
    os.makedirs(f'{tests}/audit8_salted', exist_ok=True)
    mods = []
    for stem in stems:
        src = open(f'{tests}/{stem}.rs').read()
        out, n = patch(src, crate, stem)
        header = (f'// AUDIT ROUND 8 (long-seeds): salted copy of tests/{stem}.rs, generated by\n'
                  f'// scratchpad/audit8-long-seeds/mk_salted.py. {n} seed site(s) XORed with\n'
                  f'// AUDIT8_SALT (0 = the committed seeds). Do not edit; not part of the suite.\n')
        # inner attributes / module docs must stay first: prepend only plain comments
        open(f'{tests}/audit8_salted/{stem}.rs', 'w').write(header + out)
        mods.append(stem)
        print(f'{crate}/{stem}: {n} seed sites')
    root = ['//! Audit round 8 (long-seeds): every committed randomized integration test of',
            '//! this crate, with each RNG seed XORed with `AUDIT8_SALT` (see',
            '//! `audit8_salted/*.rs`; generated, not part of the maintained suite).',
            '//! Run one module per process, as the originals are separate binaries:',
            '//! `AUDIT8_SALT=7 <binary> phase3:: --test-threads=1 [--include-ignored]`.',
            '#![allow(dead_code, unused_imports, clippy::all)]',
            '',
            '/// XORed into every RNG seed of the salted copies (0 = committed seeds).',
            'pub fn a8_salt() -> u64 {',
            '    static SALT: std::sync::OnceLock<u64> = std::sync::OnceLock::new();',
            '    *SALT.get_or_init(|| {',
            '        std::env::var("AUDIT8_SALT")',
            '            .ok()',
            '            .and_then(|v| v.parse().ok())',
            '            .unwrap_or(0)',
            '    })',
            '}',
            '']
    for stem in mods:
        root.append(f'#[path = "audit8_salted/{stem}.rs"]')
        root.append(f'mod {stem};')
    open(f'{tests}/audit8_salted.rs', 'w').write('\n'.join(root) + '\n')
